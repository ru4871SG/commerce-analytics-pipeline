-- Tasks are created suspended. EXECUTE TASK runs a suspended root, but not suspended children,
--    so resume the graph once. With no schedule, a resumed root still runs only when executed.
SELECT SYSTEM$TASK_DEPENDENTS_ENABLE('RAW.CRM.MERGE_CUSTOMERS');


-- Checking on what is waiting in a stream
SELECT "_BRAND", "ID", "STATE", "PAYMENT_STATE", "UPDATED_AT", METADATA$ACTION, METADATA$ISUPDATE
FROM RAW.CRM.ORDERS_CHANGES_STREAM;

-- Whether the tasks ran, were skipped or failed
SELECT name, state, scheduled_time, completed_time, error_message
FROM TABLE(RAW.INFORMATION_SCHEMA.TASK_HISTORY(
    SCHEDULED_TIME_RANGE_START => DATEADD('day', -2, CURRENT_TIMESTAMP())))
WHERE name LIKE 'MERGE_%'
ORDER BY scheduled_time DESC;
