-- Snowflake streams and tasks for the incremental tables
USE ROLE SYSADMIN;
USE WAREHOUSE TRANSFORMING_WH;

-- Streams: one per change table. APPEND_ONLY because the loader only ever inserts there.

CREATE STREAM IF NOT EXISTS RAW.CRM.CUSTOMERS_CHANGES_STREAM
  ON TABLE RAW.CRM.CUSTOMERS_CHANGES
  APPEND_ONLY = TRUE;

CREATE STREAM IF NOT EXISTS RAW.CRM.ORDERS_CHANGES_STREAM
  ON TABLE RAW.CRM.ORDERS_CHANGES
  APPEND_ONLY = TRUE;

CREATE STREAM IF NOT EXISTS RAW.CRM.ORDER_ITEMS_CHANGES_STREAM
  ON TABLE RAW.CRM.ORDER_ITEMS_CHANGES
  APPEND_ONLY = TRUE;

CREATE STREAM IF NOT EXISTS RAW.CRM.REFUND_PAYMENTS_CHANGES_STREAM
  ON TABLE RAW.CRM.REFUND_PAYMENTS_CHANGES
  APPEND_ONLY = TRUE;

CREATE STREAM IF NOT EXISTS RAW.CRM.MARKETING_SPEND_CHANGES_STREAM
  ON TABLE RAW.CRM.MARKETING_SPEND_CHANGES
  APPEND_ONLY = TRUE;


-- Tasks
CREATE OR REPLACE TASK RAW.CRM.MERGE_CUSTOMERS
  WAREHOUSE = TRANSFORMING_WH
AS
  MERGE INTO RAW.CRM."CUSTOMERS" AS t
  USING (
    -- the latest version of each changed row since the stream was last consumed
    SELECT * FROM RAW.CRM.CUSTOMERS_CHANGES_STREAM
    QUALIFY ROW_NUMBER() OVER (PARTITION BY "_BRAND", "ID" ORDER BY "UPDATED_AT" DESC, "_LOADED_AT" DESC) = 1
  ) AS s
  ON t."_BRAND" = s."_BRAND" AND t."ID" = s."ID"
  WHEN MATCHED THEN UPDATE SET
        "COUNTRY_CODE" = s."COUNTRY_CODE",
        "SUBSCRIBED_TO_NEWSLETTER" = s."SUBSCRIBED_TO_NEWSLETTER",
        "CREATED_AT" = s."CREATED_AT",
        "UPDATED_AT" = s."UPDATED_AT",
        "_LOADED_AT" = s."_LOADED_AT"
  WHEN NOT MATCHED THEN INSERT ("ID", "COUNTRY_CODE", "SUBSCRIBED_TO_NEWSLETTER", "CREATED_AT", "UPDATED_AT", "_BRAND", "_LOADED_AT")
    VALUES (s."ID", s."COUNTRY_CODE", s."SUBSCRIBED_TO_NEWSLETTER", s."CREATED_AT", s."UPDATED_AT", s."_BRAND", s."_LOADED_AT");

